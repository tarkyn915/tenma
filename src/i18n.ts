const messages: Record<Language, Record<TranslationKey, string>> = { en, 'zh-CN': zhCN };

export function translate(language: Language, key: TranslationKey, values: TranslationValues = {}) {
  return Object.entries(values).reduce(
    (text, [name, value]) => text.split(`{${name}}`).join(String(value)),
    messages[language][key] || en[key]
  );
}

export type MessageContent = string | { key: TranslationKey; values?: MessageValues };
type MessageValues = Record<string, string | number | MessageContent | MessageContent[]>;
type Translate = (key: TranslationKey, values?: TranslationValues) => string;

export function errorContent(error: unknown, fallback: TranslationKey): MessageContent {
  if (error instanceof LocalizedError) return { key: error.key, values: error.values };
  if (error instanceof Error) return error.message;
  return { key: fallback };
}

export function resolveMessage(content: MessageContent, t: Translate): string {
  if (typeof content === 'string') return content;
  const values: TranslationValues = {};
  for (const [name, value] of Object.entries(content.values || {})) {
    if (Array.isArray(value)) values[name] = value.map((item) => resolveMessage(item, t)).join('; ');
    else if (typeof value === 'object') values[name] = resolveMessage(value, t);
    else values[name] = value;
  }
  return t(content.key, values);
}

export function loadLanguage(): Language {
  try { return globalThis.localStorage?.getItem('tenma.language') === 'zh-CN' ? 'zh-CN' : 'en'; }
  catch { return 'en'; }
}

export function saveLanguage(language: Language) {
  try { globalThis.localStorage?.setItem('tenma.language', language); }
  catch { /* Language switching still works when persistent storage is unavailable. */ }
}

interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, values?: TranslationValues) => string;
}

export const I18nContext = createContext<I18nContextValue>({
  language: 'en',
  setLanguage: () => {},
  t: (key, values) => translate('en', key, values)
});

export function useI18n() {
  return useContext(I18nContext);
}
